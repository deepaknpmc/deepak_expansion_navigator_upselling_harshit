// You can pass additional config via defineConfig({ vite: { ... }, etc... }) if needed.
import { defineConfig } from "@lovable.dev/vite-tanstack-config";

export default defineConfig({
  // Force-on Nitro with the Vercel preset so `vite build` produces a
  // Vercel-deployable server bundle (the default outside Lovable is a
  // Vite-only build with no server — which would break our server functions
  // and MongoDB access). Overriding to Cloudflare's default is wrong here
  // because the native `mongodb` driver needs the Node runtime.
  nitro: { preset: "vercel" },
  tanstackStart: {
    // Redirect TanStack Start's bundled server entry to src/server.ts (our SSR error wrapper).
    // nitro/vite builds from this
    server: { entry: "server" },
  },
});
